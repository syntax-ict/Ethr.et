<?php

declare(strict_types=1);

namespace Tests\Accuracy\Calendar;

use DateTimeImmutable;
use DateTimeZone;
use RuntimeException;
use Tests\Accuracy\Oracle\Calendar\Odometer;

/**
 * Shared by the calendar tests. Static only: Pest loads every test file into
 * one process, so a global function or constant here could collide.
 */
final class CalendarFixtures
{
    public const FIRST_YEAR = 1892;

    public const LAST_YEAR = 2093;

    public static function tablePath(): string
    {
        return __DIR__.'/../../../../src/src/test/fixtures/ethiopian-calendar.json';
    }

    /** @return list<array{id: string, gregorian: string, ethiopian: array{0: int, 1: int, 2: int}, source: string, independent: bool, seed: bool}> */
    public static function anchors(): array
    {
        return require __DIR__.'/anchors.php';
    }

    /** @return array{gregorian: array{0: int, 1: int, 2: int}, ethiopian: array{0: int, 1: int, 2: int}, anchor: string} */
    public static function seed(): array
    {
        $seeds = array_values(array_filter(self::anchors(), static fn (array $a): bool => $a['seed']));
        if (count($seeds) !== 1) {
            throw new RuntimeException('exactly one anchor must be the seed');
        }

        return [
            'gregorian' => array_map('intval', explode('-', $seeds[0]['gregorian'])),
            'ethiopian' => $seeds[0]['ethiopian'],
            'anchor' => $seeds[0]['id'],
        ];
    }

    /** @return array<string, mixed> what the committed file must hold */
    public static function generated(): array
    {
        $seed = self::seed();

        return [
            'about' => 'Ethiopian month starts and Pagume lengths. Generated by Tests\Accuracy\Oracle\Calendar\Odometer; do not edit by hand.',
            'range' => ['ethiopian_years' => [self::FIRST_YEAR, self::LAST_YEAR], 'gregorian' => ['1900-01-01', '2100-12-31']],
            'seed' => ['gregorian' => implode('-', array_map(static fn (int $n): string => sprintf('%02d', $n), $seed['gregorian'])), 'ethiopian' => $seed['ethiopian'], 'anchor' => $seed['anchor']],
            'years' => array_map(
                static fn (array $y): array => $y,
                Odometer::table($seed, self::FIRST_YEAR, self::LAST_YEAR),
            ),
        ];
    }

    /** @return array<string, mixed> */
    public static function committed(): array
    {
        $json = file_get_contents(self::tablePath());
        if ($json === false) {
            throw new RuntimeException('cannot read '.self::tablePath());
        }

        return json_decode($json, true, 512, JSON_THROW_ON_ERROR);
    }

    public static function writeCommitted(): void
    {
        file_put_contents(self::tablePath(), json_encode(self::generated(), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n");
    }

    public static function addDays(string $date, int $days): string
    {
        return (new DateTimeImmutable($date.' 00:00:00', new DateTimeZone('UTC')))->modify(sprintf('%+d days', $days))->format('Y-m-d');
    }

    public static function daysBetween(string $from, string $to): int
    {
        $a = new DateTimeImmutable($from.' 00:00:00', new DateTimeZone('UTC'));
        $b = new DateTimeImmutable($to.' 00:00:00', new DateTimeZone('UTC'));

        return (int) $a->diff($b)->format('%r%a');
    }

    public static function monthLength(array $year, int $month): int
    {
        return $month < 13 ? 30 : $year['pagume_days'];
    }
}
